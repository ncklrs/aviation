// Generates tvos/Overhead/Sources/Core/TypeTable.swift from overhead.html so the TV app uses the exact same
// type-code -> drawing-class rules (incl. the large-cabin bizjet rule). Usage: node tools/gen_tvos_types.js
const fs=require('fs'), src=fs.readFileSync(__dirname+'/../overhead.html','utf8');
const grab=(a,b)=>{ const i=src.indexOf(a), j=src.indexOf(b,i); if(i<0||j<0) throw Error('missing '+a); return src.slice(i,j); };
const TYPES=new Function(grab('const TYPES = [','function shapeFor(')+';return TYPES;')();
const W=src.match(/const WIDE=(\/[^/]+\/)/)[1], WIDE=new Function('return '+W)();
const MED=new Function('return '+src.match(/const MEDEVAC=(\/.*\/i);?$/m)[1])();
const ev=re=>new Function('return '+src.match(re)[1])();
const QUAD=ev(/QUAD=(\/[^/]+\/)/), LEG=ev(/const LEG_RE=(\/[^/]+\/)/), EPIC=ev(/const EPIC_RE=(\/[^/]+\/)/);
const COMMON=new Function('return '+src.match(/const COMMON_TYPES=new Set\(([\s\S]*?)\);\s*$/m)[1])();
const LABEL=new Function('return '+src.match(/const LABEL=(\{.*?\});/)[1])();
const HIGH=src.match(/const HIGH_FT *= .*\|\| *(\d+)/)[1];
const q=s=>JSON.stringify(s);
let o='// GENERATED by tools/gen_tvos_types.js from overhead.html. Do not edit by hand.\n\nenum TypeTable {\n';
o+='    static let rules: [(String, String)] = [\n'+TYPES.map(([re,c])=>`        (${q(re.source)}, ${q(c)}),`).join('\n')+'\n    ]\n';
o+=`    static let wide = ${q(WIDE.source)}\n    static let medevac = ${q(MED.source)}\n`;
o+=`    static let quad = ${q(QUAD.source)}\n    static let legendary = ${q(LEG.source)}\n    static let epic = ${q(EPIC.source)}\n`;
o+=`    static let highFt: Double = ${HIGH}\n    static let helis: Set<String> = ["heli", "medheli", "tandem", "tiltrotor"]\n`;
o+='    static let common: Set<String> = ['+[...COMMON].map(q).join(', ')+']\n';
o+='    static let labels: [String: String] = [\n'+Object.entries(LABEL).map(([k,v])=>`        ${q(k)}: ${q(v)},`).join('\n')+'\n    ]\n}\n';
fs.writeFileSync(__dirname+'/../tvos/Overhead/Sources/Core/TypeTable.swift',o); console.log('TypeTable.swift', TYPES.length,'rules');
